#!/usr/bin/env bash
#!/usr/bin/env python3
"""
Vendor Tree Makefile Generator for Lenovo Tab with Clear Case (TB311FU)
Target: MediaTek Helio G88 / MT6769

Parses proprietary-files.txt and generates:
1. vendor/lenovo/TB311FU/BoardConfigVendor.mk
2. vendor/lenovo/TB311FU/TB311FU-vendor.mk
3. vendor/lenovo/TB311FU/Android.bp
"""

import sys
import os
from pathlib import Path
from typing import Dict, List, Any


DEVICE = "TB311FU"
VENDOR = "lenovo"


def generate_makefiles():
    device_dir = Path(__file__).resolve().parent
    repo_root = device_dir.parent.parent.parent
    vendor_dir = repo_root / "vendor" / VENDOR / DEVICE
    prop_files_txt = device_dir / "proprietary-files.txt"

    vendor_dir.mkdir(parents=True, exist_ok=True)

    if not prop_files_txt.exists():
        raise FileNotFoundError(f"Missing {prop_files_txt}")

    modules = []
    copy_files = []

    with open(prop_files_txt, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue

            is_module = False
            if line.startswith("-"):
                is_module = True
                line = line[1:].strip()

            if "|" in line:
                line = line.split("|", 1)[0].strip()

            if ":" in line:
                src, dest = [p.strip() for p in line.split(":", 1)]
            else:
                src = line.strip()
                dest = src

            entry = {"src": src, "dest": dest, "is_module": is_module}
            if is_module:
                modules.append(entry)
            else:
                copy_files.append(entry)

    # 1. Generate BoardConfigVendor.mk
    board_config_vendor_path = vendor_dir / "BoardConfigVendor.mk"
    with open(board_config_vendor_path, "w", encoding="utf-8") as f:
        f.write(f"""#
# Copyright (C) 2026 The LineageOS Project
#
# SPDX-License-Identifier: Apache-2.0
#
# Generated by setup-makefiles.py for {VENDOR}/{DEVICE}
#

# Vendor board configuration
BOARD_VENDOR := {VENDOR}
""")

    # Group library modules by name
    lib_modules = {}
    bin_modules = []
    jar_modules = []

    for m in modules:
        dest = m["dest"]
        is_bin = "/bin/" in dest
        is_lib = "/lib/" in dest or "/lib64/" in dest
        is_jar = dest.endswith(".jar")
        is_64 = "/lib64/" in dest

        if is_lib:
            name = Path(dest).stem
            if name not in lib_modules:
                lib_modules[name] = {}
            if is_64:
                lib_modules[name]["arm64"] = dest
            else:
                lib_modules[name]["arm"] = dest
        elif is_bin:
            name = Path(dest).name
            bin_modules.append((name, dest))
        elif is_jar:
            name = Path(dest).stem
            jar_modules.append((name, dest))

    # 2. Generate TB311FU-vendor.mk
    vendor_mk_path = vendor_dir / f"{DEVICE}-vendor.mk"
    with open(vendor_mk_path, "w", encoding="utf-8") as f:
        f.write(f"""#
# Copyright (C) 2026 The LineageOS Project
#
# SPDX-License-Identifier: Apache-2.0
#
# Generated by setup-makefiles.py for {VENDOR}/{DEVICE}
#

$(call inherit-product, $(SRC_TARGET_DIR)/product/core_64_bit.mk)

PRODUCT_SOONG_NAMESPACES += \\
    vendor/{VENDOR}/{DEVICE}

# Proprietary copy files
PRODUCT_COPY_FILES += \\
""")
        for i, cf in enumerate(copy_files):
            sep = " \\" if i < len(copy_files) - 1 else ""
            d = cf['dest']
            if d.startswith("odm/"):
                out_var = "$(TARGET_COPY_OUT_ODM)"
                sub_path = d[len("odm/"):]
            elif d.startswith("product/"):
                out_var = "$(TARGET_COPY_OUT_PRODUCT)"
                sub_path = d[len("product/"):]
            elif d.startswith("system_ext/"):
                out_var = "$(TARGET_COPY_OUT_SYSTEM_EXT)"
                sub_path = d[len("system_ext/"):]
            elif d.startswith("vendor/"):
                out_var = "$(TARGET_COPY_OUT_VENDOR)"
                sub_path = d[len("vendor/"):]
            else:
                out_var = "$(TARGET_COPY_OUT_VENDOR)"
                sub_path = d
            f.write(f"    vendor/{VENDOR}/{DEVICE}/proprietary/{d}:{out_var}/{sub_path}{sep}\n")

        f.write(f"\n# Proprietary packages to install\nPRODUCT_PACKAGES += \\\n")
        all_pkg_names = list(lib_modules.keys()) + [b[0] for b in bin_modules] + [j[0] for j in jar_modules]
        seen = set()
        unique_modules = []
        for name in all_pkg_names:
            if name not in seen:
                seen.add(name)
                unique_modules.append(name)

        for i, mod in enumerate(unique_modules):
            sep = " \\" if i < len(unique_modules) - 1 else ""
            f.write(f"    {mod}{sep}\n")

    # 3. Generate Android.bp
    android_bp_path = vendor_dir / "Android.bp"
    with open(android_bp_path, "w", encoding="utf-8") as f:
        f.write(f"""//
// Copyright (C) 2026 The LineageOS Project
//
// SPDX-License-Identifier: Apache-2.0
//
// Generated by setup-makefiles.py for {VENDOR}/{DEVICE}
//

soong_namespace {{
    imports: [
        "device/{VENDOR}/{DEVICE}",
    ],
}}
""")
        # Shared libraries
        for name, targets in lib_modules.items():
            has_64 = "arm64" in targets
            has_32 = "arm" in targets

            if has_64 and has_32:
                multilib_str = "both"
                target_str = f"""    target: {{
        android_arm64: {{
            srcs: ["proprietary/{targets['arm64']}"],
        }},
        android_arm: {{
            srcs: ["proprietary/{targets['arm']}"],
        }},
    }},"""
            elif has_64:
                multilib_str = "64"
                target_str = f"""    target: {{
        android_arm64: {{
            srcs: ["proprietary/{targets['arm64']}"],
        }},
    }},"""
            else:
                multilib_str = "32"
                target_str = f"""    target: {{
        android_arm: {{
            srcs: ["proprietary/{targets['arm']}"],
        }},
    }},"""

            f.write(f"""
cc_prebuilt_library_shared {{
    name: "{name}",
    owner: "{VENDOR}",
    strip: {{
        none: true,
    }},
{target_str}
    compile_multilib: "{multilib_str}",
    check_elf_files: false,
    prefer: true,
    soc_specific: true,
}}
""")

        # Binaries
        for name, dest in bin_modules:
            f.write(f"""
cc_prebuilt_binary {{
    name: "{name}",
    owner: "{VENDOR}",
    target: {{
        android_arm64: {{
            srcs: ["proprietary/{dest}"],
        }},
    }},
    compile_multilib: "64",
    check_elf_files: false,
    strip: {{
        none: true,
    }},
    prefer: true,
    soc_specific: true,
}}
""")

        # Jars
        for name, dest in jar_modules:
            f.write(f"""
dex_import {{
    name: "{name}",
    owner: "{VENDOR}",
    jars: ["proprietary/{dest}"],
    soc_specific: true,
}}
""")

    print(f"[OK] Generated vendor makefiles in {vendor_dir}:")
    print(f"     - {board_config_vendor_path.name}")
    print(f"     - {vendor_mk_path.name}")
    print(f"     - {android_bp_path.name}")


if __name__ == "__main__":
    generate_makefiles()
