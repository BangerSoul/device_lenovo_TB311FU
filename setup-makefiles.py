#!/usr/bin/env python3
"""
LineageOS 22 Vendor Tree Makefile Generator for Lenovo Tab M11 (TB311FU)
Target: MediaTek Helio G88 / MT6769

Parses proprietary-files.txt and generates:
1. vendor/lenovo/TB311FU/BoardConfigVendor.mk
2. vendor/lenovo/TB311FU/TB311FU-vendor.mk
3. vendor/lenovo/TB311FU/Android.bp
"""

import sys
import os
from pathlib import Path
from typing import Dict, List, Any


DEVICE = "TB311FU"
VENDOR = "lenovo"


def generate_makefiles():
    device_dir = Path(__file__).resolve().parent
    repo_root = device_dir.parent.parent.parent
    vendor_dir = repo_root / "vendor" / VENDOR / DEVICE
    prop_files_txt = device_dir / "proprietary-files.txt"

    vendor_dir.mkdir(parents=True, exist_ok=True)

    if not prop_files_txt.exists():
        raise FileNotFoundError(f"Missing {prop_files_txt}")

    modules = []
    copy_files = []

    with open(prop_files_txt, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue

            is_module = False
            if line.startswith("-"):
                is_module = True
                line = line[1:].strip()

            if "|" in line:
                line = line.split("|", 1)[0].strip()

            if ":" in line:
                src, dest = [p.strip() for p in line.split(":", 1)]
            else:
                src = line.strip()
                dest = src

            entry = {"src": src, "dest": dest, "is_module": is_module}
            if is_module:
                modules.append(entry)
            else:
                copy_files.append(entry)

    # 1. Generate BoardConfigVendor.mk
    board_config_vendor_path = vendor_dir / "BoardConfigVendor.mk"
    with open(board_config_vendor_path, "w", encoding="utf-8") as f:
        f.write(f"""#
# Copyright (C) 2026 The LineageOS Project
#
# SPDX-License-Identifier: Apache-2.0
#
# Generated by setup-makefiles.py for {VENDOR}/{DEVICE}
#

# Vendor board configuration
BOARD_VENDOR := {VENDOR}
""")

    # 2. Generate TB311FU-vendor.mk
    vendor_mk_path = vendor_dir / f"{DEVICE}-vendor.mk"
    with open(vendor_mk_path, "w", encoding="utf-8") as f:
        f.write(f"""#
# Copyright (C) 2026 The LineageOS Project
#
# SPDX-License-Identifier: Apache-2.0
#
# Generated by setup-makefiles.py for {VENDOR}/{DEVICE}
#

$(call inherit-product, $(SRC_TARGET_DIR)/product/core_64_bit.mk)

PRODUCT_SOONG_NAMESPACES += \\
    vendor/{VENDOR}/{DEVICE}

# Proprietary copy files
PRODUCT_COPY_FILES += \\
""")
        for i, cf in enumerate(copy_files):
            sep = " \\" if i < len(copy_files) - 1 else ""
            f.write(f"    vendor/{VENDOR}/{DEVICE}/proprietary/{cf['dest']}:$(TARGET_COPY_OUT_VENDOR)/{cf['dest'].replace('vendor/', '')}{sep}\n")

        f.write(f"\n# Proprietary packages to install\nPRODUCT_PACKAGES += \\\n")
        module_names = []
        for m in modules:
            base_name = Path(m["dest"]).stem
            module_names.append(base_name)

        # De-duplicate while preserving order
        seen = set()
        unique_modules = []
        for name in module_names:
            if name not in seen:
                seen.add(name)
                unique_modules.append(name)

        for i, mod in enumerate(unique_modules):
            sep = " \\" if i < len(unique_modules) - 1 else ""
            f.write(f"    {mod}{sep}\n")

    # 3. Generate Android.bp
    android_bp_path = vendor_dir / "Android.bp"
    with open(android_bp_path, "w", encoding="utf-8") as f:
        f.write(f"""//
// Copyright (C) 2026 The LineageOS Project
//
// SPDX-License-Identifier: Apache-2.0
//
// Generated by setup-makefiles.py for {VENDOR}/{DEVICE}
//

soong_namespace {{
    imports: [
        "device/{VENDOR}/{DEVICE}",
    ],
}}
""")
        for m in modules:
            dest = m["dest"]
            name = Path(dest).stem
            is_bin = "/bin/" in dest
            is_lib = "/lib/" in dest or "/lib64/" in dest
            is_jar = dest.endswith(".jar")
            is_64 = "/lib64/" in dest

            if is_lib:
                f.write(f"""
cc_prebuilt_library_shared {{
    name: "{name}",
    owner: "{VENDOR}",
    strip: {{
        none: true,
    }},
    target: {{
        android_{'arm64' if is_64 else 'arm'}: {{
            srcs: ["proprietary/{dest}"],
        }},
    }},
    compile_multilib: "{'64' if is_64 else '32'}",
    check_elf_files: false,
    prefer: true,
    soc_specific: true,
}}
""")
            elif is_bin:
                f.write(f"""
cc_prebuilt_binary {{
    name: "{name}",
    owner: "{VENDOR}",
    target: {{
        android_arm64: {{
            srcs: ["proprietary/{dest}"],
        }},
    }},
    compile_multilib: "64",
    check_elf_files: false,
    strip: {{
        none: true,
    }},
    prefer: true,
    soc_specific: true,
}}
""")
            elif is_jar:
                f.write(f"""
dex_import {{
    name: "{name}",
    owner: "{VENDOR}",
    jars: ["proprietary/{dest}"],
    soc_specific: true,
}}
""")

    print(f"[OK] Generated vendor makefiles in {vendor_dir}:")
    print(f"     - {board_config_vendor_path.name}")
    print(f"     - {vendor_mk_path.name}")
    print(f"     - {android_bp_path.name}")


if __name__ == "__main__":
    generate_makefiles()
